# https://kubernetes.io/docs/tasks/tools/included/optional-kubectl-configs-pwsh/
# but we are going to switch the completer to 'k' from 'kubectl'
Function Add-specialKAutoCompletion {
    # The completer script comes from 'kubectl completion powershell' and has to be evaluated to register it.
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingInvokeExpression', '', Justification = 'Registers the completer script generated by kubectl itself')]
    [CmdletBinding(SupportsShouldProcess)]
    param (
        [switch]$ToProfile,
        [string]$ProfilePath = $PROFILE.CurrentUserCurrentHost
    )
    $toReplace = "-CommandName 'kubectl'"
    $argCompleter = (kubectl completion powershell) -replace $toReplace, "-CommandName 'k'"
    if ($argCompleter -like 'error*') {
        throw $argCompleter
    }

    if ($null -ne $argCompleter) {
        $argCompleter | Out-String | Invoke-Expression
    }

    if ($ToProfile.IsPresent) {
        $beginMarker = '# >>> specialK completion >>>'
        $endMarker = '# <<< specialK completion <<<'
        $existing = if (Test-Path -LiteralPath $ProfilePath) { Get-Content -LiteralPath $ProfilePath -Raw } else { '' }
        if ($null -eq $existing) { $existing = '' }

        # Older versions appended a static snapshot of the completer. It is never edited here, only reported.
        if ($existing -match "Register-ArgumentCompleter[^\r\n]*-CommandName\s+'k'") {
            Write-Warning "$ProfilePath contains a static copy of the completer from an older specialK. It goes stale when kubectl updates. To remove it, delete the Register-ArgumentCompleter block for -CommandName 'k' (and the script block it uses) from that file by hand."
        }

        if ($existing.Contains($beginMarker)) {
            Write-Verbose "$ProfilePath already has the specialK completion block; nothing to do."
            return
        }

        $block = @(
            $beginMarker
            'if (Get-Command kubectl -ErrorAction SilentlyContinue) {'
            '    Add-specialKAutoCompletion'
            '}'
            $endMarker
        ) -join [Environment]::NewLine

        if ($PSCmdlet.ShouldProcess($ProfilePath, 'Add the specialK completion block')) {
            $folder = Split-Path -Path $ProfilePath -Parent
            if ($folder -and -not (Test-Path -LiteralPath $folder)) {
                New-Item -Path $folder -ItemType Directory -Force | Out-Null
            }
            $prefix = if ($existing.Length -gt 0 -and -not $existing.EndsWith("`n")) { [Environment]::NewLine } else { '' }
            Add-Content -LiteralPath $ProfilePath -Value ($prefix + $block)
        }
    }
}
